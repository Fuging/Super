-- === CHECK EMF READING ===
local function checkEMFReading()
    local currentLevel = 0
    local currentEvidence = IIllllll
    
    -- Fungsi untuk cek EMF dalam sebuah instance (item atau player)
    local function checkEMFInInstance(instance)
        if not instance then return 0, IIIIlIlI end
        
        -- Cek langsung di instance
        if instance.Name == lIIIIIllllII then
            local readingLevel = instance:GetAttribute(llIIIIII)
            if readingLevel then
                local level = tonumber(readingLevel) or 1
                if level == 5 then
                    emf5EverDetected = true
                    return level, lIlIlllll
                end
                return level, IllIIIlIIll
            end
        end
        
        -- Cek di descendants instance
        for _, child in pairs(instance:GetDescendants()) do
            if child.Name == lIIIlIlIlII then
                local readingLevel = child:GetAttribute(IlIllIllll)
                if readingLevel then
                    local level = tonumber(readingLevel) or 1
                    if level == 5 then
                        emf5EverDetected = true
                        return level, llllIIIIllIl
                    end
                    return level, llIlIIIlIIIl
                end
            end
        end
        
        return 0, lIlIIlIlIII
    end

    -- Step 1: Cek EMF di ToolsHolder semua player
    for _, player in pairs(Players:GetPlayers()) do
        local toolsHolder = player:FindFirstChild(IlIIlIlI)
        if toolsHolder then
            local emfInTools = toolsHolder:FindFirstChild(IIIlIIlIlIII)
            if emfInTools then
                local level, evidence = checkEMFInInstance(emfInTools)
                if level > 0 then
                    currentLevel = level
                    currentEvidence = evidence
                    break
                end
            end
        end
    end
    
    -- Step 2: Jika tidak ditemukan di ToolsHolder, cek di karakter player
    if currentLevel == 0 then
        for _, player in pairs(Players:GetPlayers()) do
            if player.Character then
                local level, evidence = checkEMFInInstance(player.Character)
                if level > 0 then
                    currentLevel = level
                    currentEvidence = evidence
                    break
                end
            end
        end
    end
    
    -- Step 3: Jika tidak ditemukan di player, cek di workspace.Items[IlIIIlllIlI]
    if currentLevel == 0 then
        local items = workspace:FindFirstChild(llIlIllIIllI)
        if items then
            local emfItem = items:FindFirstChild(llIlIIlI)
            if emfItem then
                local level, evidence = checkEMFInInstance(emfItem)
                if level > 0 then
                    currentLevel = level
                    currentEvidence = evidence
                end
            end
        end
    end
    
    -- Step 4: Cek juga di lokasi lain yang mungkin
    if currentLevel == 0 then
        for _, obj in pairs(workspace:GetDescendants()) do
            if obj.Name == lIIllIlIIl and (obj:IsA(IlIlIlIll) or obj:IsA(lllIIIIlIII)) then
                local level, evidence = checkEMFInInstance(obj)
                if level > 0 then
                    currentLevel = level
                    currentEvidence = evidence
                    break
                end
            end
        end
    end
    
    -- Step 5: Jika EMF5 pernah terdeteksi, selalu tampilkan evidence
    if emf5EverDetected and currentEvidence == llIIllIII then
        currentEvidence = IIIlllIIlllI
    end
    
    return currentLevel, currentEvidence
end

